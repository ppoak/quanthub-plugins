"""A-share broker domain models."""

from __future__ import annotations

from collections import deque
from dataclasses import dataclass, field
from typing import Optional

import pandas as pd

from base_strategy.evaluator import Trade


@dataclass
class AShareExecution:
    """Immutable execution record and FIFO inventory lot.

    ``ASharePosition`` stores executions as an inspectable trail and updates its
    live FIFO state incrementally when executions are applied.

    Parameters
    ----------
    execution_id:
        Execution id. Use ``AShareExecution._auto_id()`` when constructing new fills.
    datetime:
        Execution timestamp.
    side:
        One of ``BUY``, ``SELL``, ``TRANSFER``, ``WITHDRAW``, ``DIVIDEND``, or
        ``SPLIT``.
    code:
        Instrument code. Cash transfers use ``CASH``.
    quantity:
        Positive quantity. For trades, this is the number of shares.
    price:
        Execution price per share, or ``1.0`` for cash transfers.
    comm:
        Commission paid for this execution.
    """

    execution_id: str = ""
    order_id: str = ""
    account_id: str = ""
    client_id: str = ""
    source: str | None = None
    datetime: pd.Timestamp = None
    side: str = "BUY"
    code: str = ""
    quantity: float = 0.0
    price: float = 0.0
    comm: float = 0.0

    BUY = "BUY"
    SELL = "SELL"
    TRANSFER = "TRANSFER"
    WITHDRAW = "WITHDRAW"
    DIVIDEND = "DIVIDEND"
    SPLIT = "SPLIT"

    _SEQ: Optional[dict] = None

    @classmethod
    def _auto_id(cls, user_id: Optional[str] = None) -> str:
        """Generate next sequential ID: ``AShareExecution#1`` or ``AShareExecution#1:user_id``."""
        if cls._SEQ is None:
            cls._SEQ = {}
        seq = cls._SEQ.get(cls.__name__, 0) + 1
        cls._SEQ[cls.__name__] = seq
        base = f"{cls.__name__}#{seq}"
        return f"{base}:{user_id}" if user_id else base

    @property
    def cashflow(self) -> float:
        """Signed cashflow generated by this execution."""
        gross = self.quantity * self.price
        if self.side == self.BUY:
            return -gross - self.comm
        if self.side == self.SELL:
            return gross - self.comm
        if self.side in {self.TRANSFER, self.DIVIDEND}:
            return gross
        if self.side == self.WITHDRAW:
            return -gross
        return 0.0

    @property
    def timestamp(self):
        """Canonical execution timestamp alias."""
        return self.datetime

    def __str__(self):
        return (
            f"AShareExecution(#{self.execution_id}@{self.datetime} "
            f"{self.side} {self.code} {self.quantity:.0f}x${self.price:.2f})"
        )

    def __repr__(self):
        return self.__str__()


@dataclass
class AShareOrder:
    """A local A-share order and its lifecycle state.

    Orders are created by ``AShareClient`` helpers. They become accepted through
    ``AShareExchange.accept()`` and terminal after ``AShareExchange.advance()``
    matches or rejects them.

    Important statuses:

    - ``FILLED``: fully executed;
    - ``MARGIN``: insufficient sellable shares or insufficient cash;
    - ``UNQUALIFIED``: blocked by trade-state flags such as suspended or ST;
    - ``EXPIRED``: valid-until timestamp has passed.
    """

    order_id: str = ""
    account_id: str = ""
    client_id: str = ""
    source: str | None = None
    created_at: pd.Timestamp = None
    executed_at: pd.Timestamp = None
    side: str = "BUY"
    code: str = ""
    quantity: float = 0.0
    execution_type: str = "MARKET"
    limit_price: Optional[float] = None
    trigger_price: Optional[float] = None
    valid_until: Optional[pd.Timestamp] = None
    status: str = "CREATED"
    filled: float = 0.0
    amount: float = 0.0
    comm: float = 0.0
    slipped_price: float = 0.0
    executed_price: float = 0.0
    executions: list = field(default_factory=list)
    meta: dict = field(default_factory=dict)

    CREATED = "CREATED"
    SUBMITTED = "SUBMITTED"
    ACCEPTED = "ACCEPTED"
    PARTIAL = "PARTIAL"
    FILLED = "FILLED"
    CANCELED = "CANCELED"
    REJECTED = "REJECTED"
    MARGIN = "MARGIN"
    EXPIRED = "EXPIRED"
    UNQUALIFIED = "UNQUALIFIED"

    MARKET = "MARKET"
    LIMIT = "LIMIT"
    STOP = "STOP"
    STOPLIMIT = "STOPLIMIT"
    TARGET = "TARGET"
    TARGETLIMIT = "TARGETLIMIT"
    BUY = "BUY"
    SELL = "SELL"

    _SEQ: Optional[dict] = None

    @classmethod
    def _auto_id(cls, user_id: Optional[str] = None) -> str:
        """Generate next sequential ID: ``Order#1`` or ``Order#1:user_id``."""
        if cls._SEQ is None:
            cls._SEQ = {}
        seq = cls._SEQ.get(cls.__name__, 0) + 1
        cls._SEQ[cls.__name__] = seq
        base = f"{cls.__name__}#{seq}"
        return f"{base}:{user_id}" if user_id else base

    def attach(self, execution: AShareExecution) -> None:
        """Register an execution fill against this order and update counters."""
        if execution.quantity > self.quantity - self.filled:
            raise ValueError(
                f"Execution qty {execution.quantity} exceeds remaining "
                f"{self.quantity - self.filled} for order {self.order_id}"
            )
        self.executions.append(execution)
        self.filled += execution.quantity
        self.amount += execution.price * execution.quantity
        self.sync_comm()
        self.executed_at = execution.datetime

        self.slipped_price = self.amount / self.filled
        self.executed_price = (self.amount + self.comm) / self.filled

        if self.filled >= self.quantity:
            self.status = self.FILLED
        elif self.filled > 0:
            self.status = self.PARTIAL

    def sync_comm(self) -> float:
        """Synchronize order commission from attached executions."""
        self.comm = sum(float(getattr(execution, "comm", 0.0) or 0.0) for execution in self.executions)
        return self.comm

    def cancel(self) -> None:
        """Set status to CANCELED if the order is still open."""
        if self.status in {self.CREATED, self.SUBMITTED, self.ACCEPTED, self.PARTIAL}:
            self.status = self.CANCELED

    def is_alive(self, as_of: pd.Timestamp) -> bool:
        """Return whether the order is non-terminal and not expired."""
        if self.status not in {self.CREATED, self.SUBMITTED, self.ACCEPTED, self.PARTIAL}:
            return False
        if self.valid_until and as_of > self.valid_until:
            self.status = self.EXPIRED
            return False
        return True

    @property
    def remaining(self) -> float:
        return self.quantity - self.filled

    def __str__(self):
        return (
            f"Order(#{self.order_id}@{self.executed_at} "
            f"{self.execution_type} {self.side} {self.code} "
            f"{self.filled:.0f}/{self.quantity:.0f}x${self.executed_price:.2f}"
            f"[{self.status}])"
        )

    def __repr__(self):
        return self.__str__()


@dataclass
class ASharePosition:
    """Incremental FIFO position state for one instrument.

    ``executions`` remains the inspectable fact trail for this instrument, while
    current quantity, book value, and realized PnL are materialized as executions
    are applied. Historical batch views belong to ``AShareLedger``.
    """

    code: str = ""
    executions: list = field(default_factory=list)
    price: float = 0.0
    quantity: float = 0.0
    cost_value: float = 0.0
    realized_pnl_value: float = 0.0
    _lots: deque[tuple[float, float]] = field(default_factory=deque, init=False, repr=False)
    _buy_quantity_by_date: dict = field(default_factory=dict, init=False, repr=False)

    def __post_init__(self) -> None:
        if not self.executions:
            return
        executions = list(self.executions)
        self.executions = []
        self.quantity = 0.0
        self.cost_value = 0.0
        self.realized_pnl_value = 0.0
        self._lots.clear()
        self._buy_quantity_by_date.clear()
        for execution in executions:
            self.apply_execution(execution)

    @property
    def shares_held(self) -> float:
        """Current net position quantity."""
        return self.quantity

    @property
    def book_value(self) -> float:
        """Current FIFO cost basis of remaining live lots."""
        return self.cost_value

    @property
    def market_value(self) -> float:
        return self.shares_held * self.price

    @property
    def unrealized_pnl(self) -> float:
        return self.market_value - self.book_value

    @property
    def realized_pnl(self) -> float:
        """Current realized PnL accumulated from FIFO lot consumption."""
        return self.realized_pnl_value

    def apply_execution(self, execution: AShareExecution) -> None:
        """Apply one execution to the current position state."""
        self.executions.append(execution)
        if execution.side == AShareExecution.BUY:
            self._apply_buy(execution)
        elif execution.side == AShareExecution.SELL:
            self._apply_sell(execution)

    def entry_prices_map(self) -> dict[pd.Timestamp, float]:
        """Return {datetime: price} for all BUY lots."""
        return {
            execution.datetime: float(execution.price)
            for execution in self.executions
            if execution.side == AShareExecution.BUY and execution.datetime
        }

    def update_price(self, price: float) -> None:
        """Record the latest market price for mark-to-market."""
        self.price = price

    def available_quantity(self, datetime, *, enforce_t1: bool = True) -> float:
        """Return sellable quantity at ``datetime`` using materialized T+1 state."""
        if not enforce_t1 or datetime is None:
            return self.shares_held
        as_of_date = pd.Timestamp(datetime).date()
        blocked = self._buy_quantity_by_date.get(as_of_date, 0.0)
        return max(self.shares_held - blocked, 0.0)

    def _apply_buy(self, execution: AShareExecution) -> None:
        quantity = float(execution.quantity)
        price = float(execution.price)
        self.quantity += quantity
        self.cost_value += quantity * price
        self._lots.append((quantity, price))
        if execution.datetime is not None:
            buy_date = pd.Timestamp(execution.datetime).date()
            self._buy_quantity_by_date[buy_date] = self._buy_quantity_by_date.get(buy_date, 0.0) + quantity

    def _apply_sell(self, execution: AShareExecution) -> None:
        quantity = float(execution.quantity)
        price = float(execution.price)
        self.quantity -= quantity
        to_sell = quantity
        while to_sell > 1e-9 and self._lots:
            lot_qty, lot_price = self._lots[0]
            consumed = min(lot_qty, to_sell)
            self.cost_value -= consumed * lot_price
            self.realized_pnl_value += consumed * (price - lot_price)
            lot_qty -= consumed
            to_sell -= consumed
            if lot_qty <= 1e-9:
                self._lots.popleft()
            else:
                self._lots[0] = (lot_qty, lot_price)
        if abs(self.quantity) <= 1e-9:
            self.quantity = 0.0
        if abs(self.cost_value) <= 1e-9:
            self.cost_value = 0.0

    def trades(self) -> list[Trade]:
        """Compute round-trip trades from this position via FIFO lot matching."""
        result: list[Trade] = []
        if not self.executions:
            return result

        sorted_executions = sorted(
            self.executions, key=lambda execution: execution.datetime or pd.Timestamp.min
        )
        open_lots: deque = deque()
        current_open: dict | None = None

        for execution in sorted_executions:
            if execution.side == AShareExecution.BUY:
                open_lots.append(
                    (
                        execution.datetime,
                        execution.price,
                        execution.quantity,
                        execution.comm,
                        execution.execution_id,
                    )
                )
                if current_open is None:
                    current_open = {
                        "code": self.code,
                        "open_execution_id": execution.execution_id,
                        "open_datetime": str(execution.datetime) if execution.datetime else None,
                        "open_price": execution.price,
                        "open_comm": execution.comm,
                        "quantity": execution.quantity,
                    }
            elif execution.side == AShareExecution.SELL and execution.quantity > 0:
                to_sell = execution.quantity
                total_cost = 0.0
                total_open_comm = 0.0
                sold_qty = 0.0

                while to_sell > 1e-9 and open_lots:
                    lot_dt, lot_price, lot_qty, lot_comm, lot_did = open_lots[0]
                    consumed = min(lot_qty, to_sell)
                    consumed_comm = consumed * lot_comm / lot_qty if lot_qty > 0 else 0.0
                    total_cost += consumed * lot_price
                    total_open_comm += consumed_comm
                    sold_qty += consumed
                    to_sell -= consumed

                    if consumed >= lot_qty - 1e-9:
                        open_lots.popleft()
                    else:
                        open_lots[0] = (
                            lot_dt,
                            lot_price,
                            lot_qty - consumed,
                            lot_comm - consumed_comm,
                            lot_did,
                        )

                realized_pnl = (
                    execution.price * sold_qty
                    - total_cost
                    - total_open_comm
                    - execution.comm
                )
                result.append(
                    Trade(
                        code=self.code,
                        open_execution_id=current_open["open_execution_id"] if current_open else None,
                        open_timestamp=current_open["open_datetime"] if current_open else None,
                        open_price=current_open["open_price"] if current_open else None,
                        open_fee=round(total_open_comm, 4),
                        quantity=sold_qty,
                        close_execution_id=execution.execution_id,
                        close_timestamp=str(execution.datetime) if execution.datetime else None,
                        close_price=execution.price,
                        close_fee=execution.comm,
                        realized_pnl=realized_pnl,
                    )
                )

                if not open_lots:
                    current_open = None

        return result
